    <h1>How to file a copyright — overview</h1>
    <p>Copyright protects original works of authorship fixed in a tangible medium — software, writings, art, music, videos. Registration is with the <strong>U.S. Copyright Office</strong>, not the USPTO.</p>
    <h2 style="font-family:var(--font-display);color:var(--navy-deep);font-size:20px">The path</h2>
    <ol class="mock-guide-steps">
      <li>Confirm the work is original and already written down, recorded, or saved (not just an idea in your head).</li>
      <li>Understand what registration adds: public record, and important timing if you later need to sue.</li>
      <li>Prepare the application and deposit copies per Copyright Office rules for your type of work.</li>
      <li>File online through copyright.gov (eCO) and track the claim.</li>
    </ol>
    <h2 style="font-family:var(--font-display);color:var(--navy-deep);font-size:20px">What copyright covers (and does not)</h2>
    <p>Copyright protects the <em>expression</em> in a work: the actual words, images, music, video, or code. It does not protect ideas, facts, methods of operation, or names and short phrases. If your value is in how something works, look at the <a href="<?php echo esc_url( help_url( 'guides-patent' ) ); ?>">patent guide</a>. If it is in a name or logo, see the <a href="<?php echo esc_url( help_url( 'guides-trademark' ) ); ?>">trademark guide</a>.</p>
    <h2 style="font-family:var(--font-display);color:var(--navy-deep);font-size:20px">Protected already, so why register?</h2>
    <p>Copyright exists automatically once a work is fixed in a tangible form. Registration is optional, but for U.S. works it is generally needed before you can sue for infringement, and registering early can make you eligible for statutory damages and attorney&rsquo;s fees. It also creates a public record of your claim. More in <a href="<?php echo esc_url( help_url( 'a-copyright-basics' ) ); ?>">copyright basics for creators and software</a>.</p>
    <h2 style="font-family:var(--font-display);color:var(--navy-deep);font-size:20px">Who owns the copyright?</h2>
    <ul>
      <li>Usually the person who created the work.</li>
      <li>If it was made by an employee as part of the job, the employer may own it (work made for hire).</li>
      <li>If you hired a freelancer or developer, do not assume you own the result. Get a written agreement that says who owns what.</li>
    </ul>
    <h2 style="font-family:var(--font-display);color:var(--navy-deep);font-size:20px">What you need to register</h2>
    <ul>
      <li>The author&rsquo;s name and details, and whether the work was made for hire.</li>
      <li>The year of completion and, if published, the date and place of first publication.</li>
      <li>A copy (a &ldquo;deposit&rdquo;) of the work in the form the Copyright Office requires for its type. Software has special deposit rules.</li>
      <li>The filing fee, which depends on the type of claim.</li>
    </ul>
    <p>The Copyright Office&rsquo;s circulars explain each type of work in detail. You may add a &copy; notice to your work. It is not required, but it tells people the work is claimed.</p>
