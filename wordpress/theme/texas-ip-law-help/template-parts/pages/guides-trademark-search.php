    <h1>How to search for a trademark before you pick a name</h1>
    <p>Choosing a name that someone else already uses for similar goods or services can lead to a refused application, a demand letter, or a costly rebrand. A search before you commit takes a few hours and can save months. This guide shows a practical first check you can run yourself.</p>
    <div class="help-callout"><p><strong>Keep expectations realistic.</strong> A self-run search catches many problems but not all of them. If you are about to invest in packaging, signage, or advertising, a professional clearance search is worth the cost.</p></div>

    <h2>The path</h2>
    <ol class="mock-guide-steps">
      <li><strong>Write down exactly what you will sell</strong> under the name, and who your customers are. Conflicts depend on the goods or services, not only on the name.</li>
      <li><strong>Search the USPTO trademark database</strong> for your exact name. Use the official Trademark Search system, which is free.</li>
      <li><strong>Search variations.</strong> Try different spellings, plurals, phrases that sound the same, translations, and names that mean the same thing. Marks do not have to be identical to conflict.</li>
      <li><strong>Check related goods and services.</strong> A similar name for a related business can still be a problem. Look at what each owner actually sells.</li>
      <li><strong>Look for unregistered users.</strong> Search the web, app stores, social media, and state business records. People using a name in business can have rights even without a federal registration.</li>
      <li><strong>Check the domain name and social handles</strong> you would need.</li>
      <li><strong>Record what you found</strong> with dates and links, so you can show your reasoning later.</li>
      <li><strong>Only then decide</strong> whether to file a federal application. See the <a href="<?php echo esc_url( help_url( 'guides-trademark' ) ); ?>">trademark guide</a>.</li>
    </ol>

    <h2>How to read a result</h2>
    <ul>
      <li><strong>Live registration or application, similar name, related goods:</strong> a real risk. Talk to an attorney before you proceed.</li>
      <li><strong>Dead or abandoned record:</strong> not always safe. The owner may still be using the name.</li>
      <li><strong>Identical name in an unrelated field:</strong> may be fine, but famous names get broader protection.</li>
      <li><strong>Nothing found:</strong> encouraging, not proof. Keep looking at variations.</li>
    </ul>
    <p>A word or two on name strength: invented or arbitrary names are usually easier to register than names that simply describe the product. Read more in <a href="<?php echo esc_url( help_url( 'a-tm-clearance' ) ); ?>">trademark clearance before you launch a brand</a>.</p>

