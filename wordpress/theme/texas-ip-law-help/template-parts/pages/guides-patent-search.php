    <h1>How to search for existing patents (prior art)</h1>
    <p>Before you spend money on a patent filing, it helps to see what already exists. Anything the public could already see before you file is called <strong>prior art</strong>, and it is what an examiner will compare your invention against. A first search you can do yourself, for free, in an afternoon.</p>
    <div class="help-callout"><p><strong>Keep expectations realistic.</strong> A do-it-yourself search is a useful filter. It cannot prove that nothing similar exists, and it is not an opinion on whether you can get a patent.</p></div>

    <h2>What counts as prior art</h2>
    <ul>
      <li>Issued patents and published patent applications, from the United States and other countries.</li>
      <li>Articles, theses, conference papers, and websites.</li>
      <li>Products that were sold or shown publicly, including old ones.</li>
      <li>Your own earlier public disclosures. See <a href="<?php echo esc_url( help_url( 'a-disclosure' ) ); ?>">public disclosure before you file</a>.</li>
    </ul>

    <h2>The path</h2>
    <ol class="mock-guide-steps">
      <li><strong>Describe the invention in plain words.</strong> One paragraph on the problem and your solution. Then list the key features that you think are new.</li>
      <li><strong>Make a keyword list.</strong> Include synonyms and different ways other people might describe the same thing (&ldquo;fastener,&rdquo; &ldquo;clip,&rdquo; &ldquo;coupling&rdquo;).</li>
      <li><strong>Start broad in Google Patents.</strong> It is easy to use and searches full text. Try several keyword combinations and note the closest results.</li>
      <li><strong>Search the USPTO&rsquo;s Patent Public Search.</strong> It is the official free database. Use it to search U.S. patents and published applications by keyword and by classification.</li>
      <li><strong>Use classification codes.</strong> When you find a close patent, look up its classification codes and search by them. This finds similar inventions that use different words.</li>
      <li><strong>Read the claims, not just the title and abstract.</strong> The claims show what a patent actually covers.</li>
      <li><strong>Look beyond patents.</strong> Search for products, papers, and websites. Many inventions are blocked by things that were never patented.</li>
      <li><strong>Write down what you found.</strong> Keep dated notes: the searches you ran, the closest results, and how yours differs.</li>
    </ol>

    <h2>What to do with the results</h2>
    <ul>
      <li>If you find something very close, do not panic. Differences in structure, use, or results may still matter. Bring it to an attorney.</li>
      <li>If you find nothing close, that is encouraging but not proof. Your search may have missed it.</li>
      <li>Do not copy language from patents into your own filing.</li>
    </ul>

