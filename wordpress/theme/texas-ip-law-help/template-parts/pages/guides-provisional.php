    <h1>Provisional patent application — what it is and how to use it</h1>
    <p>A provisional application is a lower-cost first filing that can lock in an early U.S. filing date for your invention. It is never examined and never becomes a patent on its own, so it is a first step, not the finish line. This guide covers when people use one, what to put in it, and the clock that starts when you file.</p>
    <p>New to patents? Read <a href="<?php echo esc_url( help_url( 'guides-patent' ) ); ?>">How to file a patent</a> first, or compare the two filings in <a href="<?php echo esc_url( help_url( 'a-provisional' ) ); ?>">provisional vs. non-provisional</a>.</p>

    <h2>The path</h2>
    <ol class="mock-guide-steps">
      <li><strong>Check that a provisional fits.</strong> It suits inventors who need an early date while they build, test, or look for funding, and who will follow up with a full application.</li>
      <li><strong>Write a thorough description.</strong> The provisional only helps for what it actually describes. Explain how the invention is made and used, include drawings, and describe variations you can think of.</li>
      <li><strong>File with the USPTO</strong> through its online filing system and pay the filing fee for your entity size. The USPTO publishes the current fees.</li>
      <li><strong>Mark the 12-month date</strong> on a calendar the day you file. It does not move.</li>
      <li><strong>Follow up before it expires.</strong> File a non-provisional application (or an eligible international application) that claims the provisional&rsquo;s date, or the benefit is lost.</li>
    </ol>

    <h2>What to include</h2>
    <ul>
      <li>A clear written description of the problem and how your invention solves it.</li>
      <li>Drawings or photos with labels, even if rough.</li>
      <li>Step-by-step explanation of how to make and use it, including materials and settings where they matter.</li>
      <li>Alternatives and variations, so the filing supports more than your first prototype.</li>
      <li>Test results or data, if you have them.</li>
    </ul>
    <p>Formal patent claims are not required in a provisional, but a few draft claims can help organize what you want to protect.</p>

    <h2>What a provisional does not do</h2>
    <ul>
      <li>It is <strong>not examined</strong> and cannot be enforced as a patent.</li>
      <li>It does <strong>not extend</strong> the 12-month deadline.</li>
      <li>It does <strong>not undo</strong> public disclosures you made before filing. See <a href="<?php echo esc_url( help_url( 'a-disclosure' ) ); ?>">public disclosure before you file</a>.</li>
      <li>A thin or vague provisional may not support the claims you want later.</li>
    </ul>

