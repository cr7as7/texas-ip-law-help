    <h1>How to file a patent — overview for inventors</h1>
    <p>Use this path if you made a new and useful invention (machine, process, composition, or improvement). Names and logos are usually <a href="<?php echo esc_url( help_url( 'guides-trademark' ) ); ?>">trademarks</a>. Books, art, and code are usually <a href="<?php echo esc_url( help_url( 'guides-copyright' ) ); ?>">copyright</a>.</p>
    <h2 style="font-family:var(--font-display);color:var(--navy-deep);font-size:20px">The path</h2>
    <ol class="mock-guide-steps">
      <li><strong>Document</strong> the invention: drawings, how it works, dates of conception, and anyone you already told.</li>
      <li><strong>Look around</strong> — a prior-art search (USPTO Patent Public Search and published papers) so you know what is already out there.</li>
      <li><strong>Choose a first filing.</strong> A <a href="<?php echo esc_url( help_url( 'a-provisional' ) ); ?>">provisional</a> can lock an early date at lower cost; a non-provisional is examined and can become an issued patent.</li>
      <li><strong>File with the USPTO</strong> — often with a registered patent attorney or agent. Self-filers still use official forms.</li>
      <li><strong>Keep deadlines.</strong> A provisional gives you up to 12 months to file a matching non-provisional. Office actions have their own clocks.</li>
    </ol>
    <h2 style="font-family:var(--font-display);color:var(--navy-deep);font-size:20px">Which kind of patent?</h2>
    <ul>
      <li><strong>Utility</strong>: how something works or is made. The most common.</li>
      <li><strong>Design</strong>: the ornamental appearance of a useful item.</li>
      <li><strong>Plant</strong>: certain new plant varieties.</li>
    </ul>
    <p>Most inventors need a utility patent. A product can also have a design patent for its look. See <a href="<?php echo esc_url( help_url( 'a-patent-basics' ) ); ?>">patent basics</a> for what each covers.</p>
    <h2 style="font-family:var(--font-display);color:var(--navy-deep);font-size:20px">Before you spend money</h2>
    <ul>
      <li><a href="<?php echo esc_url( help_url( 'guides-patent-search' ) ); ?>">Search for existing patents</a> with free tools so you know what is already out there.</li>
      <li>Learn the tests: <a href="<?php echo esc_url( help_url( 'a-patentability' ) ); ?>">is my idea patentable?</a></li>
      <li>Hold off on public demos, posts, and sales. Read <a href="<?php echo esc_url( help_url( 'a-disclosure' ) ); ?>">public disclosure before you file</a>.</li>
      <li>Consider a <a href="<?php echo esc_url( help_url( 'guides-provisional' ) ); ?>">provisional application</a> if you need an early date.</li>
    </ul>
    <h2 style="font-family:var(--font-display);color:var(--navy-deep);font-size:20px">Cost and timing</h2>
    <p>Costs depend on the invention. You pay USPTO fees, which are lower for small and micro entities, plus attorney or agent fees if you hire help. Examination commonly takes more than a year, and office actions add time and cost. Check the current <a href="https://www.uspto.gov/learning-and-resources/fees-and-payment/uspto-fee-schedule" target="_blank" rel="noopener">USPTO fee schedule</a>, and ask any attorney for a written quote.</p>
    <h2 style="font-family:var(--font-display);color:var(--navy-deep);font-size:20px">Who can file</h2>
    <p>Only the true inventors may be named, and a company can own the patent by assignment. An individual inventor may file on their own. Representing others before the USPTO in patent matters generally requires a registered patent attorney or agent. A U.S. patent covers the United States only; ask early if you need protection abroad.</p>
    <div class="help-stop">
      <h2>Stop and talk to an attorney if…</h2>
      <ul>
        <li>You already showed the invention at a trade show, on a website, or to investors.</li>
        <li>Someone wants you to assign or license rights, or you have a co-inventor dispute.</li>
        <li>You received a USPTO office action or a deadline inside six months.</li>
        <li>The invention is a medical device, software with a business method, or anything you are unsure is even patent-eligible.</li>
      </ul>
