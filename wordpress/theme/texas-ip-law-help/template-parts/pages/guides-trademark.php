    <h1>How to file a trademark — overview</h1>
    <p>Use this path to protect a <strong>brand</strong> — name, logo, or slogan you use in commerce. A trademark is not a patent. If you invented a product, start with the <a href="<?php echo esc_url( help_url( 'guides-patent' ) ); ?>">patent guide</a> as well.</p>
    <h2 style="font-family:var(--font-display);color:var(--navy-deep);font-size:20px">The path</h2>
    <ol class="mock-guide-steps">
      <li><strong>Pick a strong mark</strong> (distinctive, not a generic product name).</li>
      <li><strong>Clearance search</strong> — USPTO Trademark Search plus common-law uses (web, state filings). Filing without a search is how conflicts start.</li>
      <li><strong>Identify goods and services</strong> and how the mark is already used, or will be used, in commerce.</li>
      <li><strong>File with the USPTO online</strong> (older materials call this TEAS) with the right specimens and fees.</li>
      <li><strong>Watch the application</strong> — office actions, publication, then maintenance after registration.</li>
    </ol>
    <h2 style="font-family:var(--font-display);color:var(--navy-deep);font-size:20px">What can be a trademark</h2>
    <p>Words, names, logos, slogans, and sometimes sounds, colors, or product shapes, as long as customers see them as a sign of who is behind the goods or services. A <strong>service mark</strong> is the same idea for services. People say &ldquo;trademark&rdquo; for both.</p>
    <h2 style="font-family:var(--font-display);color:var(--navy-deep);font-size:20px">Strong names and weak names</h2>
    <ul>
      <li><strong>Invented or arbitrary</strong> names are usually the easiest to register and the hardest for others to copy.</li>
      <li><strong>Suggestive</strong> names hint at a quality without describing it.</li>
      <li><strong>Descriptive</strong> names describe the product and often need proof that customers see them as a brand.</li>
      <li><strong>Generic</strong> names cannot be trademarks. See <a href="<?php echo esc_url( help_url( 'a-tm-clearance' ) ); ?>">trademark clearance before you launch</a>.</li>
    </ul>
    <h2 style="font-family:var(--font-display);color:var(--navy-deep);font-size:20px">Already using it, or planning to?</h2>
    <p>You can apply based on use in commerce if you are already selling under the mark, or based on a genuine intention to use it. Which basis you choose affects the paperwork and the timing, so read the USPTO instructions carefully. Run a search first: see the <a href="<?php echo esc_url( help_url( 'guides-trademark-search' ) ); ?>">trademark search guide</a>.</p>
    <h2 style="font-family:var(--font-display);color:var(--navy-deep);font-size:20px">After you file</h2>
    <ul>
      <li>An examining attorney at the USPTO reviews the application and may send an <strong>office action</strong> with objections you must answer by a deadline.</li>
      <li>If it passes review, the mark is published so others can oppose it.</li>
      <li>After registration you must file maintenance documents on the USPTO&rsquo;s schedule, or the registration can be cancelled. Calendar these dates.</li>
      <li>You may use the &trade; symbol any time you claim a mark. Use &reg; only after federal registration.</li>
    </ul>
